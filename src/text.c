static const int FONT_LEN = (int)(sizeof(FONT) / sizeof(FONT[0]));

/* Separacion entre caracteres, en pixeles de la fuente. */
#define GLYPH_GAP 1

static const unsigned char *glyph_rows(char c)
{
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');

    for (int i = 0; i < FONT_LEN; ++i)
        if (FONT[i].ch == c) return FONT[i].rows;

    return FONT[0].rows;  /* lo desconocido se dibuja como espacio */
}

int text_width(const char *s, int scale)
{
    int n = 0;
    while (s[n] != '\0') ++n;
    if (n == 0) return 0;

    return (n * (GLYPH_W + GLYPH_GAP) - GLYPH_GAP) * scale;
}

void text_draw(SDL_Renderer *ren, int x, int y, int scale,
               SDL_Color color, const char *s)
{
    SDL_SetRenderDrawColor(ren, color.r, color.g, color.b, color.a);

    /* Los pixeles encendidos se juntan en un solo arreglo y se dibujan de una
     * sola llamada, en lugar de pedir un rectangulo a la vez. */
    SDL_Rect rects[GLYPH_W * GLYPH_H];
    int pen = x;

    for (int i = 0; s[i] != '\0'; ++i) {
        const unsigned char *rows = glyph_rows(s[i]);
        int n = 0;

        for (int r = 0; r < GLYPH_H; ++r) {
            for (int c = 0; c < GLYPH_W; ++c) {
                if ((rows[r] >> (GLYPH_W - 1 - c)) & 1) {
                    rects[n].x = pen + c * scale;
                    rects[n].y = y + r * scale;
                    rects[n].w = scale;
                    rects[n].h = scale;
                    ++n;
                }
            }
        }

        if (n > 0) SDL_RenderFillRects(ren, rects, n);
        pen += (GLYPH_W + GLYPH_GAP) * scale;
    }
}
